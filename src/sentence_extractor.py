import re


def extract_sentences(text: str) -> list[str]:
    """
    Split an LLM response into individual sentences.

    Args:
        text: The response generated by an LLM.

    Returns:
        A list containing the extracted sentences.
    """
    if not text or not text.strip():
        return []

    # Split after sentence-ending punctuation.
    sentences = re.split(r'(?<=[.!?])\s+', text.strip())

    # Remove extra whitespace and empty entries.
    return [sentence.strip() for sentence in sentences if sentence.strip()]


if __name__ == "__main__":
    sample_text = (
        "The Eiffel Tower is in Paris. "
        "It was built in 1889. "
        "It is located in London."
    )

    sentences = extract_sentences(sample_text)

    for index, sentence in enumerate(sentences, start=1):
        print(f"{index}. {sentence}")